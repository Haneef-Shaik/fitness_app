import { createHash } from 'node:crypto';

// The launch exercise seed (CT-1 box 3; docs/architecture/003 §7; QA-1 F-6). One PL/pgSQL block over one JSON payload:
// for each catalogue (id, version) it inserts the row when absent, leaves an identical catalogue row alone, and stops
// the whole block with an error when a member-owned row holds that id at any version (checked first, before the
// (id, version) lookup and the insert) or an existing catalogue row differs. It has no other statement, so it cannot
// change or remove any row, member-owned or not.

export const SEED_TAG = 'ct1_seed';
const DOLLAR_QUOTE = `$${SEED_TAG}$`;

/** Provenance as the existing `source` column can hold it (no licence or source-version columns exist yet; MB-2). */
export const sourceText = (exercise) => `${exercise.provenance.source}@${exercise.provenance.sourceVersion}; licence ${exercise.provenance.licence}; slug ${exercise.slug}`;

export function sqlLiteral(text) {
  if (typeof text !== 'string' || text.includes('\u0000')) throw new Error('A SQL literal must be a string without NUL bytes');
  return `'${text.replaceAll("'", "''")}'`;
}

/** Rows in public.exercises terms, in catalogue order. Muscles and equipment use their display names. */
export function seedRows(catalogue) {
  const muscleName = new Map(catalogue.muscles.map((muscle) => [muscle.id, muscle.name]));
  return catalogue.exercises.map((exercise) => ({
    id: exercise.id,
    version: exercise.version,
    name: exercise.name,
    loggingType: exercise.loggingType,
    loadBasis: exercise.loadBasis,
    multiplier: exercise.multiplier,
    equipment: exercise.equipmentName,
    primaryMuscles: exercise.primary.map((id) => muscleName.get(id)),
    secondaryMuscles: exercise.secondary.map((id) => muscleName.get(id)),
    instructions: exercise.instructions,
    aliases: [...exercise.aliases],
    source: sourceText(exercise),
  }));
}

const ordered = (field) => `array(select t.x from jsonb_array_elements_text(rec->'${field}') with ordinality as t(x, n) order by t.n)`;

/** The seed SQL for the given rows. Throws on text that could leave the literal or the dollar-quoted block. */
export function seedSqlFromRows(rows, { contentVersion = 'unversioned' } = {}) {
  if (!Array.isArray(rows) || rows.length === 0) throw new Error('The seed needs at least one row');
  const payload = JSON.stringify(rows);
  if (payload.includes('\\')) throw new Error('Seed text must not contain a backslash, a double quote or a control character (JSON would escape it with a backslash)');
  if (payload.includes('$')) throw new Error(`Seed text must not contain a dollar sign, which could end the ${DOLLAR_QUOTE} block`);
  const payloadSha256 = createHash('sha256').update(payload, 'utf8').digest('hex');
  const sql = [
    `-- FitLog launch exercise catalogue (CT-1), content ${contentVersion}: ${rows.length} catalogue rows, payload sha256 ${payloadSha256}.`,
    '-- Generated by scripts/content/build-seed.mjs from content/. Edit the content files, never this output.',
    '-- It inserts the catalogue rows that are missing and leaves every existing row as it is. It stops with an error,',
    '-- writing nothing, when a member-owned row holds any version of a catalogue id or when an existing catalogue row differs from',
    '-- this seed; a changed record needs a new version, never an in-place edit.',
    `do ${DOLLAR_QUOTE}`,
    'declare',
    `  seed jsonb := ${sqlLiteral(payload)}::jsonb;`,
    '  rec jsonb;',
    '  existing public.exercises%rowtype;',
    '  member_version integer;',
    '  wanted_primary text[];',
    '  wanted_secondary text[];',
    '  wanted_aliases text[];',
    'begin',
    '  for rec in select value from jsonb_array_elements(seed) loop',
    // A member may not hold a catalogue id at any version (review M1). The same-version branch below stays as a backstop.
    "    select m.version into member_version from public.exercises m where m.id = (rec->>'id')::uuid and m.owner_id is not null order by m.version limit 1;",
    '    if found then',
    "      raise exception 'CT-1 seed: catalogue key % version % is held by a member-owned row', rec->>'id', member_version using errcode = '23505';",
    '    end if;',
    `    wanted_primary := ${ordered('primaryMuscles')};`,
    `    wanted_secondary := ${ordered('secondaryMuscles')};`,
    `    wanted_aliases := ${ordered('aliases')};`,
    "    select e.* into existing from public.exercises e where e.id = (rec->>'id')::uuid and e.version = (rec->>'version')::integer;",
    '    if found then',
    '      if existing.owner_id is not null then',
    "        raise exception 'CT-1 seed: catalogue key % version % is held by a member-owned row', rec->>'id', rec->>'version' using errcode = '23505';",
    '      end if;',
    "      if existing.name is distinct from rec->>'name'",
    "        or existing.logging_type is distinct from rec->>'loggingType'",
    "        or existing.load_basis is distinct from rec->>'loadBasis'",
    "        or existing.multiplier is distinct from (rec->>'multiplier')::integer",
    "        or existing.equipment is distinct from rec->>'equipment'",
    '        or existing.primary_muscles is distinct from wanted_primary',
    '        or existing.secondary_muscles is distinct from wanted_secondary',
    "        or existing.instructions is distinct from rec->>'instructions'",
    '        or existing.aliases is distinct from wanted_aliases',
    "        or existing.source is distinct from rec->>'source' then",
    "        raise exception 'CT-1 seed: catalogue row % version % differs from this seed; publish a new version instead of editing it', rec->>'id', rec->>'version' using errcode = '23514';",
    '      end if;',
    '      continue;',
    '    end if;',
    '    insert into public.exercises (id, version, owner_id, name, logging_type, load_basis, multiplier, equipment, primary_muscles, secondary_muscles, instructions, aliases, archived, source)',
    "    values ((rec->>'id')::uuid, (rec->>'version')::integer, null, rec->>'name', rec->>'loggingType', rec->>'loadBasis', (rec->>'multiplier')::integer, rec->>'equipment', wanted_primary, wanted_secondary, rec->>'instructions', wanted_aliases, false, rec->>'source');",
    '  end loop;',
    'end',
    `${DOLLAR_QUOTE};`,
    '',
  ].join('\n');
  return { sql, payloadSha256 };
}

/** The seed for a validated catalogue: { sql, rows, payloadSha256 }. */
export function buildExerciseSeedSql(catalogue) {
  const rows = seedRows(catalogue);
  return { ...seedSqlFromRows(rows, { contentVersion: catalogue.contentVersion }), rows };
}
