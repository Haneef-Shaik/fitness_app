@dataclass(frozen=True, slots=True)
class Dish:
    slug: str
    name: str
    basis: str                                  # "fndds:<id>" | "sr:<id>" | "recipe"
    portions: tuple[tuple[str, float], ...]
    aliases: tuple[str, ...] = ()
    recipe: Recipe = ()
    yield_g: float | None = None                # cooked weight of `recipe`
    note: str = ""
    #: Search prior (see Food.search_weight). The dishes people log daily sit
    #: a little higher than the occasional ones.
    weight: int = 50


def fndds(slug, name, fdc_id, portions, aliases=(), note="", weight=50) -> Dish:
    return Dish(slug, name, f"fndds:{fdc_id}", tuple(portions), tuple(aliases),
                note=note, weight=weight)


def sr(slug, name, fdc_id, portions, aliases=(), note="", weight=50) -> Dish:
    return Dish(slug, name, f"sr:{fdc_id}", tuple(portions), tuple(aliases),
                note=note, weight=weight)


def recipe(slug, name, ingredients: Recipe, yield_g, portions, aliases=(), note="",
           weight=50) -> Dish:
    return Dish(slug, name, "recipe", tuple(portions), tuple(aliases),
                tuple(ingredients), yield_g, note, weight)


