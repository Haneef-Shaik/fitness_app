"""The curated Indian dishes — how each one is valued, and where the number comes from.

Read by `scripts/import_usda.py`, which writes `app/seed/data/indian_foods.json`.
Edit here, re-run the import, commit both.

**Why not IFCT 2017?** The Indian Food Composition Tables (ICMR-NIN) are the
best source for Indian foods, but they are © NIN and published as a book; the
machine-readable copies online (e.g. the `ifct2017` npm/GitHub package, AGPL,
formerly MIT) are third-party transcriptions whose licence cannot grant rights
to NIN's data, and the Indian Nutrient Databank publishes no licence at all.
Neither may be redistributed in an app. So every figure here is traceable to a
public-domain USDA record instead, in one of three ways (`basis`):

- `fndds:<fdc id>` — the dish exists in USDA FNDDS 2021–2023, which has a
  surprising number of Indian dishes (dal, idli, dosa, biryani, samosa…).
  Its published per-100 g values are used as-is.
- `sr:<fdc id>` — a single SR Legacy food under its Indian name.
- `recipe` — calculated by FitLog from a standard home recipe (below, in
  grams) using SR Legacy values for each ingredient, divided by the cooked
  weight. This is how FNDDS and IFCT's own recipe tables are built; the recipe
  is the citation. Home cooking varies by ±20% or more (mostly the oil), so
  the output is rounded to whole kcal and one decimal of a gram — no more
  precision than a recipe can honestly claim.

Stated substitutions, because SR Legacy has no record for them: **paneer** is
valued as queso blanco (the same acid-set fresh whole-milk cheese); **poha**
(flattened rice) as raw white rice; **chana dal / kala chana** as chickpeas;
**jaggery** as brown sugar. Spices under ~1% of a dish's weight are omitted.

**Portions are household estimates**, the measures an Indian kitchen uses:
1 katori (small bowl) ≈ 150 g of dal, curry or sabzi; 1 plate of rice or
biryani ≈ 250 g; a roti ≈ 40 g. FNDDS's own portions are kept where it has
them. A portion is only a way to enter grams — the food stays per 100 g.
"""
